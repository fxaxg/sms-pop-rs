const DICTS: Record<Lang, Dict> = { zh, en };

export const LangContext = createContext<Lang>("zh");

/** 取当前语言的字典。 */
export function useT(): Dict {
  return DICTS[useContext(LangContext)];
}

/** 非 React 场景直接拿字典。 */
export function dict(lang: Lang): Dict {
  return DICTS[lang];
}
